import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const frontendDir = resolve(scriptDir, '..');
const packageJsonPath = resolve(frontendDir, 'package.json');
const targetPath = resolve(frontendDir, '../supabase/functions/recommend/version.ts');

const packageJson = JSON.parse(readFileSync(packageJsonPath, 'utf8'));
const version = packageJson.version;

if (typeof version !== 'string' || version.trim().length === 0) {
  throw new Error('frontend/package.json version must be a non-empty string.');
}

const targetDir = dirname(targetPath);
if (!existsSync(targetDir)) {
  throw new Error(
    `Target directory does not exist: ${targetDir}\n` +
      `Run 'supabase functions new recommend' or check the repo layout.`,
  );
}

const nextContent =
  `// Generated from frontend/package.json by frontend/scripts/sync-edge-function-version.mjs.\n` +
  `// Do not edit this file directly.\n` +
  `export const appVersion = ${JSON.stringify(version)};\n`;
const currentContent = existsSync(targetPath) ? readFileSync(targetPath, 'utf8') : null;

if (currentContent === nextContent) {
  process.stdout.write(`sync:function-version: already up to date (${version})\n`);
} else {
  writeFileSync(targetPath, nextContent);
  process.stdout.write(`sync:function-version: wrote version ${version} to ${targetPath}\n`);
}
